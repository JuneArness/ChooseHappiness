// Builds supabase/seed.sql from the launch content in /content. Safe to re-run:
// existing rows are left alone (on conflict do nothing), so admin edits are never overwritten.
// Run: npm run seed
import { readFileSync, writeFileSync } from "node:fs";

const read = (f) => JSON.parse(readFileSync(new URL(`../content/${f}`, import.meta.url), "utf8"));
const wellness = read("wellness.json");
const perspective = read("perspective.json");
const pages = read("pages.json");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v ?? []))}::jsonb`;
const arr = (a) => `array[${(a ?? []).map(q).join(",")}]::text[]`;

export const TOPICS = [
  // pillar, slug, title, summary, icon
  ["wellness", "understanding-emotions", "Understanding emotions", "What feelings are, why they show up, and how to work with them.", "heart"],
  ["wellness", "stress", "Stress management", "How stress works in the body and practical ways to ease the load.", "leaf"],
  ["wellness", "anxiety", "Anxiety education", "Understanding worry and anxiety, and when to reach out for help.", "wind"],
  ["wellness", "depression", "Depression awareness", "Recognizing depression and the support that can help.", "cloud"],
  ["wellness", "emotional-regulation", "Emotional regulation", "Skills for riding out strong feelings without being swept away.", "waves"],
  ["wellness", "self-compassion", "Self-compassion", "Treating yourself with the kindness you'd offer a friend.", "hands"],
  ["wellness", "mindfulness", "Mindfulness", "Paying attention to the present moment, gently and on purpose.", "sun"],
  ["wellness", "sleep-routines", "Sleep and routines", "Rhythms and habits that support rest and steadiness.", "moon"],
  ["wellness", "grief-loss", "Grief and loss", "Making room for grief, in whatever shape it takes.", "feather"],
  ["wellness", "healthy-relationships", "Healthy relationships", "What healthy connection looks like and how to nurture it.", "people"],
  ["wellness", "communication-boundaries", "Communication and boundaries", "Saying what you need and protecting what matters.", "chat"],
  ["wellness", "loneliness-connection", "Loneliness and connection", "Understanding loneliness and small ways to reconnect.", "link"],
  ["wellness", "burnout", "Burnout", "Spotting burnout and finding a more sustainable pace.", "battery"],
  ["wellness", "resilience", "Resilience", "Building the capacity to bend without breaking.", "sprout"],
  ["wellness", "seeking-help", "Seeking professional help", "How to find care and what to expect when you reach out.", "compass"],
  ["perspective", "reframing", "Reframing a difficult moment", "Noticing your first interpretation and considering a more balanced one.", "frame"],
  ["perspective", "facts-vs-assumptions", "Facts versus assumptions", "Separating what you know from what you fear or predict.", "scale"],
  ["perspective", "control", "What remains within my control?", "Finding realistic actions without blaming yourself for every outcome.", "compass"],
  ["perspective", "meaning", "Finding meaning without minimizing pain", "Growth and meaning, without pretending suffering is good.", "sunrise"],
  ["perspective", "gratitude", "Gratitude without toxic positivity", "Noticing what matters while honoring what hurts.", "sun"],
  ["perspective", "setbacks", "Learning from setbacks", "Lessons, options and achievable next steps after things go wrong.", "path"],
  ["perspective", "relationships-perspective", "Communication and relationships", "Assumptions, listening, boundaries and conflict.", "people"],
  ["perspective", "decisions", "Decision-making", "Weighing choices, values, risks and consequences.", "branch"],
];

const out = [];
out.push("-- Generated by scripts/generate-seed.mjs from /content. Do not edit by hand.");
out.push("begin;");
TOPICS.forEach(([pillar, slug, title, summary, icon], i) => {
  out.push(`insert into public.topics (slug, pillar, title, summary, icon, sort) values (${q(slug)}, ${q(pillar)}, ${q(title)}, ${q(summary)}, ${q(icon)}, ${i}) on conflict do nothing;`);
});

const articles = [...wellness, ...perspective.articles, ...perspective.exercises];
const topicSlugs = new Set(TOPICS.map((t) => t[1]));
for (const a of articles) {
  if (!topicSlugs.has(a.topic)) throw new Error(`Unknown topic ${a.topic} for ${a.slug}`);
  const tags = [a.pillar === "wellness" ? "mental wellness" : "perspective", a.kind === "exercise" ? "guided exercise" : "article"];
  out.push(`insert into public.articles (slug, topic_slug, pillar, kind, title, summary, body, intro, example, closing, steps, takeaways, prompts, exercise, sources, related, tags, sensitive, content_note, professional_note, evidence_note, reading_minutes, featured, published, published_at)
values (${q(a.slug)}, ${q(a.topic)}, ${q(a.pillar)}, ${q(a.kind)}, ${q(a.title)}, ${q(a.summary)}, ${q(a.body ?? "")}, ${q(a.intro ?? "")}, ${q(a.example ?? "")}, ${q(a.closing ?? "")}, ${j(a.steps)}, ${j(a.takeaways)}, ${j(a.prompts)}, ${q(a.exercise ?? "")}, ${j(a.sources)}, ${j(a.related)}, ${arr(tags)}, ${a.sensitive ? "true" : "false"}, ${q(a.content_note ?? "")}, ${q(a.professional_note ?? "")}, ${q(a.evidence_note ?? "")}, ${Number(a.reading_minutes ?? a.minutes ?? 5)}, ${["understanding-your-emotions", "reframing", "mindful-pause", "understanding-stress"].includes(a.slug) ? "true" : "false"}, true, now()) on conflict (slug) do nothing;`);
}

for (const p of pages.pages) {
  out.push(`insert into public.pages (slug, title, summary, body, needs_professional_review) values (${q(p.slug)}, ${q(p.title)}, ${q(p.summary ?? "")}, ${q(p.body)}, ${p.needs_professional_review ? "true" : "false"}) on conflict do nothing;`);
}
// The evidence summaries shown under the manifesto are stored as a page so admins can edit them.
out.push(`insert into public.pages (slug, title, summary, body, needs_professional_review) values ('evidence-summary', 'What research suggests', 'Short evidence notes shown under the manifesto. Body is JSON.', ${q(JSON.stringify(pages.evidence_summary, null, 2))}, true) on conflict do nothing;`);

out.push("insert into public.reflection_prompts (text) select x from unnest(" + arr(pages.prompts) + ") x where not exists (select 1 from public.reflection_prompts);");
pages.forum_categories.forEach((c) => {
  out.push(`insert into public.forum_categories (slug, name, description, sort) values (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${Number(c.sort)}) on conflict do nothing;`);
});
pages.journeys.forEach((jr, i) => {
  out.push(`insert into public.journeys (slug, title, summary, minutes, steps, sort) values (${q(jr.slug)}, ${q(jr.title)}, ${q(jr.summary)}, ${Number(jr.minutes ?? 10)}, ${j(jr.steps)}, ${i}) on conflict do nothing;`);
});
out.push("commit;");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`seed.sql: ${TOPICS.length} topics, ${articles.length} articles/exercises, ${pages.pages.length + 1} pages, ${pages.prompts.length} prompts, ${pages.forum_categories.length} categories, ${pages.journeys.length} journeys`);
